// «СВОДКА В 10:00 ЗНАЧИТ В 10:00».
//
// Событие и кнопка отправляются сразу — их вызывает сам человек. А вот сводку
// по расписанию кто-то должен вспомнить, и этот кто-то — часы.
//
// ПОЧЕМУ НЕ ПЛАНИРОВЩИК. Тариф Vercel Hobby даёт расписание РАЗ В СУТКИ и с
// точностью «в течение часа» — на «ровно в 10:00» это не годится. Внешний
// планировщик умеет точно, но его надо завести и прописать руками. Обещать
// точное время, которое на деле зависит от чужой настройки, нечестно.
//
// ЧАСЫ ЕСТЬ И ЗДЕСЬ. Пока у кого-то открыта CRM, вкладка раз в минуту
// спрашивает сервер «пора?». В 10:00 ответ становится «да», и сводка уходит.
// Вопрос стоит двух маленьких чтений (настройки и состояние рассылки) —
// дешевле, чем один тик парсера, — а тяжёлый прогон поднимается, только когда
// действительно пора. Решает это сервер (whatIsDue в api/notify-run.mjs), а не
// браузер: часы на телефоне сотрудника могут врать, а подписаться на чужие
// уведомления через эту точку всё равно нельзя.
//
// СПРАШИВАЕТ ЛЮБАЯ ОТКРЫТАЯ ВКЛАДКА, А НЕ ТОЛЬКО РЕДАКТОР.
//
// Сначала спрашивала только вкладка с editor-lock — чтобы пять вкладок не
// задавали один вопрос впятером. Расплата пришла сразу: 17 сентября сводка,
// назначенная на 10:00, ушла в 11:11, потому что в десять утра вкладки-редактора
// просто не было открыто, и час держал запасной прогон Actions. Часы, которые
// идут не всегда, — это не часы.
//
// Лишние вопросы теперь не страшны: вопрос стоит двух маленьких узлов, а если
// дело дойдёт до отправки, замок на стороне сервера пропустит ровно один прогон,
// остальные получат «занято». Поэтому пусть спрашивают все — вероятность, что в
// десять утра открыт хоть кто-то, несравнимо выше.
//
// СПРАШИВАЕМ И СРАЗУ ПРИ ОТКРЫТИИ, И ПРИ ВОЗВРАТЕ НА ВКЛАДКУ. Иначе человек,
// открывший CRM в 10:00:05, ждал бы ещё целый интервал. Пока вкладку не видно,
// молчим: ночью экран заблокирован, спрашивать не у кого и незачем.
//
// Плюс тик — подстраховка для событий, чья мгновенная отправка не дошла: раз в
// три минуты сервер поднимает полный прогон и добирает их.
//
// Сбой тика МОЛЧИТ. Это фон, о котором человек не просил: он открыл CRM, а не
// «проверку расписания». Ошибку показывать не за что.
export const TICK_MS = 120_000;

export async function askIfDue({ getToken, fetchImpl = fetch } = {}) {
  try {
    const token = await getToken();
    if (!token) return { ok: false, code: "no_auth" };
    const r = await fetchImpl("/api/notify-run", {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
      body: JSON.stringify({ kind: "due" }),
    });
    let payload = null;
    try { payload = await r.json(); } catch { /* пустой ответ — не беда */ }
    return (r.ok && payload?.ok) ? { ok: true, ...payload } : { ok: false, code: payload?.code || "failed" };
  } catch {
    return { ok: false, code: "unreachable" };
  }
}

// Возвращает функцию остановки. Время и таймеры берутся снаружи — чтобы тест
// не ждал по-настоящему минуту.
export function startNotifyTicker({
  ask,
  isVisible = () => true,
  setTimer = setInterval,
  clearTimer = clearInterval,
  intervalMs = TICK_MS,
  onVisible = null,        // подписка на «вкладку снова видно»; null — не нужна
} = {}) {
  let busy = false;
  const beat = async () => {
    // Не наслаиваем вопросы друг на друга: полный прогон занимает секунду-две,
    // и за это время может подойти следующий тик.
    if (busy || !isVisible()) return;
    busy = true;
    try { await ask(); } catch { /* фон молчит */ } finally { busy = false; }
  };
  beat();                                   // сразу, не дожидаясь первого тика
  const id = setTimer(beat, intervalMs);
  const off = onVisible ? onVisible(beat) : null;
  return () => { clearTimer(id); if (typeof off === "function") off(); };
}
