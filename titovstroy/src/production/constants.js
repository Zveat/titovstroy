// Построить элементы чек-листа из шаблона (строки или объекты {section,text})
export const buildChecklistItems = (template, genId) => template.map(x =>
  typeof x === "string"
    ? { id: genId(), text: x, done: false, responsible: "", note: "" }
    : { id: genId(), text: x.text, section: x.section || "", done: false, responsible: "", note: "" }
);

