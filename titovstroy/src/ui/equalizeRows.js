// КНОПКИ ОДНОГО РЯДА — ОДНОГО РАЗМЕРА, ВО ВСЕХ РАЗДЕЛАХ.
//
// ЗАЧЕМ. Размеры набирались по месту, и в одном ряду стояли соседи разной высоты и очень
// разной длины: замерено на экране 390px — в шапке Главной 153 / 94 / 77 по ширине, в панели
// объектов 111x31 рядом с 138x36, ниже 70x33, 63x34 и 110x33. Ряд выглядит собранным наспех.
//
// ПОЧЕМУ НЕ CSS. «Ширина по самой длинной кнопке ряда» на CSS не выражается: либо константа —
// её пришлось бы подбирать каждому ряду и переподбирать, когда в подписи вырастет счётчик
// («Корзина (7)» → «Корзина (12)»), — либо растягивание на всю строку, и кнопки разъезжаются
// во всю ширину экрана. Поэтому меряем.
//
// ПОЧЕМУ САМИ ИЩЕМ РЯДЫ, А НЕ ПОМЕЧАЕМ РУКАМИ. Разделов и подразделов под два десятка, рядов —
// полсотни. Помечая по одному, гарантированно что-то пропустишь, и снова будет «где-то длинные,
// где-то нет». Ряд опознаём по признаку: у одного родителя две и больше видимых кнопок с
// подписями.
//
// РАЗМЕР НЕ УВЕЛИЧИВАЕМ. Ряд подтягивается к САМОЙ БОЛЬШОЙ кнопке ЭТОГО ЖЕ ряда и ни к чему
// больше. Попытка заодно поднять всё до 44px «под палец» была отвергнута владельцем: кнопки
// стали огромными, а прежний размер его устраивал.

// Кнопка-значок (✕, 🗑, ←, ▼) размер соседей не задаёт и сама его не принимает: растянутый на
// полтораста пикселей крестик выглядит поломкой. Отличаем по подписи — у значка её нет, только
// сам символ. Эмодзи в UTF-16 занимает две единицы, поэтому считаем символы, а не длину строки.
export function isIconButton(text) {
  return [...String(text ?? "").trim()].length <= 2;
}

// Ряды, которые трогать нельзя, помечены этим классом. Сейчас это чипы фильтров: подписи у них
// от «Все» до «Согласование сметы», и общая ширина развернула бы девять чипов в пять рядов
// пустоты. Владелец с этим согласился отдельно.
export const KEEP_CLASS = "tap-keep";

// Собираем ряды ОТ КНОПОК, а не обходом всех элементов: кнопок на экране десятки, а узлов
// тысячи, и проход по ним на каждой перерисовке стоил бы дороже самой задачи.
// ПОЛОСЫ НАВИГАЦИИ ВЫРАВНИВАТЬ НЕЛЬЗЯ. Вкладки Админки (13 штук) и разделы Финансов (8) — это
// не панель кнопок, а полоса-меню: подписи там от «👥 Сотрудники» до «📑 Шаблоны документов», и
// общая ширина выстраивает их в столбик во всю ширину экрана. Поймано на живом прогоне: на
// телефоне Админка превратилась в стену из тринадцати кнопок в столбик.
// Отличаем по количеству: панель — это два-пять действий рядом, шесть и больше подряд бывает
// только у меню и фильтров. Порог грубый, зато не требует помечать полсотни мест руками;
// точечно ряд можно исключить классом tap-keep.
export const MAX_ROW = 5;

export function collectRows(buttons) {
  const byParent = new Map();
  for (const b of buttons) {
    if (isIconButton(b.textContent)) continue;
    const parent = b.parentElement;
    if (!parent || parent.classList?.contains(KEEP_CLASS)) continue;
    if (!byParent.has(parent)) byParent.set(parent, []);
    byParent.get(parent).push(b);
  }
  return [...byParent.values()].filter((row) => row.length >= 2 && row.length <= MAX_ROW);
}

// Наибольшие ширина и высота ряда.
//
// МЕРЯЕМ offsetWidth/offsetHeight, А НЕ getBoundingClientRect. У приложения свой масштаб
// интерфейса (по умолчанию 90%), и rect отдаёт размер НА ЭКРАНЕ: кнопка шириной 153 меряется
// как 138. Это число уходит обратно в min-width, где его снова умножают на масштаб, — и вместо
// 153 получается 124. Поймано на живом прогоне: ряд «138 / 124 / 124» вместо трёх одинаковых.
// offset* отдаёт размер в тех же единицах, в которых его потом читает CSS, поэтому сходится
// при любом масштабе. Та же ловушка уже описана в App.jsx у верхней полосы предупреждений.
export function rowSize(buttons, measure) {
  let width = 0, height = 0;
  for (const b of buttons) {
    const r = measure(b) || {};
    if (!r.width || !r.height) continue;          // скрытая кнопка размер не задаёт
    width = Math.max(width, r.width);
    height = Math.max(height, r.height);
  }
  return { width: Math.ceil(width), height: Math.ceil(height) };
}

// Пишем ПРЯМО НА КНОПКИ, а не классом на ряд: разметку рисует React, и класс, добавленный мимо
// него, при следующей перерисовке пропадёт. Отдельные свойства inline-стиля React не трогает —
// он убирает только то, что само было в его style.
export function applySize(buttons, { width, height }) {
  let changed = 0;
  const w = width > 0 ? `${width}px` : "", h = height > 0 ? `${height}px` : "";
  for (const b of buttons) {
    if (b.style.minWidth === w && b.style.minHeight === h) continue;
    b.style.minWidth = w;
    b.style.minHeight = h;
    changed++;
  }
  return changed;
}

// Проход по экрану.
//
// ТРИ ЗАХОДА НА ВЕСЬ ЭКРАН, а не по ряду: сначала со всех кнопок снимаем прежний размер, потом
// читаем размеры, потом записываем. Иначе чтение сразу после записи заставляет браузер
// пересчитывать раскладку на каждом ряду по отдельности, а рядов на экране десятки.
export function equalizeRows(root) {
  if (!root?.querySelectorAll) return 0;
  const rows = collectRows(root.querySelectorAll("button"));
  if (!rows.length) return 0;
  for (const row of rows) for (const b of row) { b.style.minWidth = ""; b.style.minHeight = ""; }
  const sizes = rows.map((row) => rowSize(row, (b) => ({ width: b.offsetWidth, height: b.offsetHeight })));
  let changed = 0;
  rows.forEach((row, i) => { changed += applySize(row, sizes[i]); });
  return changed;
}
