// КОГДА УСТРОЙСТВО СОТРУДНИКА ДОЛЖНО ВЫЙТИ ПО КНОПКЕ ВЛАДЕЛЬЦА.
//
// Владелец нажимает «Разлогинить» — в личный узел сотрудника кладётся время нажатия.
// Устройство слушает свой узел и решает по этому правилу.
//
// СРАВНИВАЕМ СО ВРЕМЕНЕМ ОТКРЫТИЯ ВКЛАДКИ, а не просто «отметка есть». Отметка остаётся в базе
// навсегда, и без сравнения человек вылетал бы сразу после КАЖДОГО следующего входа — то есть
// одно нажатие закрыло бы ему работу насовсем. Это главное, ради чего правило вынесено отдельно
// и проверяется тестами.
//
// Значение приходит из базы строкой (иногда в кавычках — так его отдаёт REST), поэтому разбор
// снисходительный: мусор и пустое означают «ничего не делать», а не ошибку.
export function shouldForceLogout(raw, sessionStartedAt) {
  const at = parseInt(String(raw ?? "").replace(/"/g, "").trim(), 10);
  if (!Number.isFinite(at) || at <= 0) return false;
  return at > (Number(sessionStartedAt) || 0);
}
